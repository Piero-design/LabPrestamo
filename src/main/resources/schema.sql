CREATE TABLE IF NOT EXISTS app_user (
 username VARCHAR(80) PRIMARY KEY, password VARCHAR(100) NOT NULL,
 name VARCHAR(120) NOT NULL, role VARCHAR(20) NOT NULL CHECK(role IN ('ESTUDIANTE','ENCARGADO'))
);
CREATE TABLE IF NOT EXISTS equipment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) UNIQUE NOT NULL, name VARCHAR(120) NOT NULL, category VARCHAR(80) NOT NULL,
 state VARCHAR(20) NOT NULL CHECK(state IN ('OPERATIVO','MANTENIMIENTO'))
);
CREATE TABLE IF NOT EXISTS reservation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 equipment_id BIGINT NOT NULL REFERENCES equipment(id), username VARCHAR(80) NOT NULL REFERENCES app_user(username),
 starts_at TIMESTAMP NOT NULL, ends_at TIMESTAMP NOT NULL, reason VARCHAR(500) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('PENDIENTE','APROBADA','RECHAZADA','CANCELADA','PRESTADO','DEVUELTO')),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, decided_by VARCHAR(80), decision_note VARCHAR(500),
 delivered_at TIMESTAMP, delivered_by VARCHAR(80), initial_condition VARCHAR(500),
 returned_at TIMESTAMP, returned_by VARCHAR(80), final_condition VARCHAR(500),
 CHECK(ends_at > starts_at)
);
CREATE INDEX IF NOT EXISTS idx_reservation_equipment ON reservation(equipment_id, starts_at, ends_at);
